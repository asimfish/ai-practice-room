// Offline teaching rule only; no quote lookup or product call.
export function assessGenerationBudget({limit,spent,reserved,nextEstimate,attempts,maxAttempts=2,unit,estimateUnit}) {
  const reasons=[];
  const amounts=[limit,spent,reserved,nextEstimate];
  if(!amounts.every(v=>typeof v==='number'&&Number.isFinite(v)&&v>=0))reasons.push('金额或报价缺失/无效');
  if(typeof unit!=='string'||!unit.trim()||typeof estimateUnit!=='string'||unit!==estimateUnit)reasons.push('费用单位未知或不同');
  if(!Number.isInteger(attempts)||attempts<0||!Number.isInteger(maxAttempts)||maxAttempts<1)reasons.push('次数或次数上限无效');
  else if(attempts>=maxAttempts)reasons.push('单镜请求次数已到上限');
  const remaining=[limit,spent,reserved].every(v=>typeof v==='number'&&Number.isFinite(v)&&v>=0)?limit-spent-reserved:null;
  if(remaining!==null&&typeof nextEstimate==='number'&&Number.isFinite(nextEstimate)&&nextEstimate>=0&&nextEstimate>remaining)reasons.push('下一请求超过可用余额');
  return {allow:reasons.length===0,status:reasons.length?'STOP':'READY',remaining,reasons};
}
